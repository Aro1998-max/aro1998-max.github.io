  /* Список пар для настройки проверок в ПО */
  EIR.clashes = function (s) {
    var M = EIR.clashMatrix(s), out = [], diag = [];
    var nt = {}; M.notes.forEach(function (x) { x.pairs.forEach(function (p) { nt[p] = x.text; }); });
    M.codes.forEach(function (ci, i) {
      M.codes.forEach(function (cj, j) {
        var x = M.cells[i][j]; if (!x) return;
        var row = [ci, i === j ? ci + ' (внутри раздела)' : cj, x.tol != null ? x.tol : '—', x.c === 'К' ? 'Критическая' : 'Предупреждение', nt[i === j ? ci : ci + '–' + cj] || ''];
        (i === j ? diag : out).push(row);
      });
    });
    return out.concat(diag);
  };

