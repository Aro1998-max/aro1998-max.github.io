  /* Матрица: codes — марки; cells[i][j] (i<=j) — null | {c:'К'|'П', tol:число|null, key}; notes — по типам пар */
  EIR.clashMatrix = function (s) {
    var ms = marksOf(s), tol = s.acc.tol, n = ms.length;
    function grp(m) {
      if (m.id === 'KZH' || m.id === 'KM') return 'struct';
      if (m.id === 'AR') return 'arch';
      if (m.id === 'GP') return 'site';
      if (m.id === 'TX') return 'tech';
      if (m.grp === 'Наружные сети') return 'ext';
      return 'mep';
    }
    var rule = {
      'struct|mep': 'К', 'struct|tech': 'К', 'arch|mep': 'К', 'arch|tech': 'К', 'mep|mep': 'К', 'mep|tech': 'К', 'tech|tech': 'К',
      'arch|struct': 'П', 'site|ext': 'К', 'ext|ext': 'К', 'struct|ext': 'К', 'site|struct': 'П', 'arch|site': 'П', 'site|tech': 'П'
    };
    var note = {
      'struct|mep': 'Проход сетей допускается только через отверстия, предусмотренные в ЦИМ конструкций',
      'struct|tech': 'Проход сетей допускается только через отверстия, предусмотренные в ЦИМ конструкций',
      'arch|mep': 'Проход сетей через стены и перекрытия — через отверстия; сети в подвесных потолках не являются коллизией',
      'arch|struct': 'Проверка наложения слоёв и отделки на конструкции',
      'mep|mep': 'С учётом изоляции',
      'mep|tech': 'С учётом изоляции и зон обслуживания оборудования',
      'site|ext': 'Глубина заложения, пересечения с покрытиями и ограждениями',
      'ext|ext': 'Пересечения и нормативные расстояния между сетями',
      'diag': 'Дублирующиеся и пересекающиеся элементы одного раздела'
    };
    var cells = [], notes = {};
    for (var i = 0; i < n; i++) {
      cells.push([]);
      for (var j = 0; j < n; j++) {
        if (j < i) { cells[i].push(null); continue; }
        var a = grp(ms[i]), b = grp(ms[j]), key, c, t = tol;
        if (i === j) { key = 'diag'; c = (a === 'arch' || a === 'site') ? 'П' : 'К'; if (c === 'П') t = null; }
        else { key = [a, b].sort().join('|'); c = rule[key]; }
        if (!c) { cells[i].push(null); continue; }
        cells[i].push({ c: c, tol: t, key: key });
        if (note[key]) (notes[note[key]] = notes[note[key]] || []).push(i === j ? ms[i].code : ms[i].code + '–' + ms[j].code);
      }
    }
    return { codes: ms.map(function (m) { return m.code; }), cells: cells,
      notes: Object.keys(notes).map(function (k) { return { text: k, pairs: notes[k] }; }) };
  };
  EIR.CLASH_LEGEND = '«К» — критическая коллизия, препятствует приёмке; «П» — предупреждение, допускается при обосновании в реестре замечаний; число — допуск, мм; пустая ячейка — пара не проверяется. Диагональ — проверка внутри раздела.';
